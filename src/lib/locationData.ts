export const ALL_INDIAN_STATES = Object.keys(INDIAN_STATES_DISTRICTS);

export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return INDIAN_STATES_DISTRICTS['Tamil Nadu'];
  const matched = Object.keys(INDIAN_STATES_DISTRICTS).find(
    (k) => k.toLowerCase() === stateName.trim().toLowerCase()
  );
  if (matched) return INDIAN_STATES_DISTRICTS[matched];
  return ['Madurai', 'Chennai', 'Coimbatore', 'Salem', 'Other'];
}
